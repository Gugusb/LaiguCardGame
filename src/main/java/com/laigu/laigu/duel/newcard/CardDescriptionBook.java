    /** 录入一条：普通主描述、金质主描述、金质焕章行（无则「焕章：无」）。 */
    private static void put(String artifactId, String commonDesc, String goldDesc, String goldBonus)
    {
        MAIN.put(artifactId + "_common", commonDesc);
        MAIN.put(artifactId + "_gold", goldDesc);
        GOLD.put(artifactId + "_gold", "焕章：" + goldBonus);
        GOLD.put(artifactId + "_common", "");
    }

    private CardDescriptionBook() {}

    /** 主描述；未收录的 id 返回空串（校验测试兜底）。 */
    public static String description(String variantId)
    {
        return MAIN.getOrDefault(variantId, "");
    }

    /** 焕章行；普通卡空串，金卡无加成返回「焕章：无」。 */
    public static String goldDescription(String variantId)
    {
        return GOLD.getOrDefault(variantId, "");
    }
